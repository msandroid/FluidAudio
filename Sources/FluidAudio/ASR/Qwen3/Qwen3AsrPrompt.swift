import Foundation

/// Prompt token construction for Qwen3-ASR, matching the official `qwen_asr` package.
///
/// Official chat template (`Qwen/Qwen3-ASR-0.6B` `chat_template.json`):
/// ```
/// <|im_start|>system\n{context}<|im_end|>\n
/// <|im_start|>user\n<|audio_start|><|audio_pad|>…<|audio_end|><|im_end|>\n
/// <|im_start|>assistant\n
/// ```
/// The system turn carries optional *context* (biasing text), not a task instruction.
/// A language is forced by appending `language {Name}<asr_text>` after the assistant header
/// (`Qwen3ASRModel._build_text_prompt` → `force_language`); the model then emits the
/// transcript directly instead of predicting `language X<asr_text>` itself.
enum Qwen3AsrPrompt {

    /// Token ID of `language` (the text before the language name in the forced prefix).
    static let languageWordTokenId: Int32 = 11_528

    /// `language {englishName}<asr_text>` token IDs per language.
    ///
    /// Generated by tokenizing the official prompt with the Qwen/Qwen3-ASR-0.6B tokenizer
    /// (`AutoTokenizer.from_pretrained(..., fix_mistral_regex=True)`, as `qwen_asr` loads it):
    /// `tokenize(base + f"language {name}<asr_text>")[len(tokenize(base)):]`, where `base` is the
    /// chat template above with an empty system turn. Every row decodes back to its exact string.
    /// Replaces the former system-turn `taskTokens`, whose IDs decoded to
    /// `agnıs the Oper to … text.` for all 30 languages.
    static let forcedLanguagePrefixTokens: [Qwen3AsrConfig.Language: [Int32]] = [
        .chinese: [11_528, 8453, 151_704],  // language Chinese<asr_text>
        .english: [11_528, 6364, 151_704],  // language English<asr_text>
        .cantonese: [11_528, 72_366, 2367, 151_704],  // language Cantonese<asr_text>
        .arabic: [11_528, 34_117, 151_704],  // language Arabic<asr_text>
        .german: [11_528, 5938, 151_704],  // language German<asr_text>
        .french: [11_528, 8585, 151_704],  // language French<asr_text>
        .spanish: [11_528, 15_154, 151_704],  // language Spanish<asr_text>
        .portuguese: [11_528, 42_188, 151_704],  // language Portuguese<asr_text>
        .indonesian: [11_528, 58_829, 151_704],  // language Indonesian<asr_text>
        .italian: [11_528, 14_811, 151_704],  // language Italian<asr_text>
        .korean: [11_528, 16_134, 151_704],  // language Korean<asr_text>
        .russian: [11_528, 8522, 151_704],  // language Russian<asr_text>
        .thai: [11_528, 26_392, 151_704],  // language Thai<asr_text>
        .vietnamese: [11_528, 48_477, 151_704],  // language Vietnamese<asr_text>
        .japanese: [11_528, 10_769, 151_704],  // language Japanese<asr_text>
        .turkish: [11_528, 23_734, 151_704],  // language Turkish<asr_text>
        .hindi: [11_528, 43_980, 151_704],  // language Hindi<asr_text>
        .malay: [11_528, 79_140, 151_704],  // language Malay<asr_text>
        .dutch: [11_528, 23_234, 151_704],  // language Dutch<asr_text>
        .swedish: [11_528, 30_109, 151_704],  // language Swedish<asr_text>
        .danish: [11_528, 43_680, 151_704],  // language Danish<asr_text>
        .finnish: [11_528, 57_853, 151_704],  // language Finnish<asr_text>
        .polish: [11_528, 31_984, 151_704],  // language Polish<asr_text>
        .czech: [11_528, 33_150, 151_704],  // language Czech<asr_text>
        .filipino: [11_528, 62_417, 151_704],  // language Filipino<asr_text>
        .persian: [11_528, 49_861, 151_704],  // language Persian<asr_text>
        .greek: [11_528, 17_860, 151_704],  // language Greek<asr_text>
        .hungarian: [11_528, 56_769, 151_704],  // language Hungarian<asr_text>
        .macedonian: [11_528, 56_452, 75_491, 151_704],  // language Macedonian<asr_text>
        .romanian: [11_528, 73_597, 151_704],  // language Romanian<asr_text>
    ]

    /// Prompt tokens for one utterance: empty system turn, audio placeholders, assistant header,
    /// and — when `language` is set — the official forced-language prefix.
    static func promptTokens(numAudioFrames: Int, language: Qwen3AsrConfig.Language?) -> [Int32] {
        var tokens: [Int32] = []

        // System turn (empty context).
        tokens.append(Int32(Qwen3AsrConfig.imStartTokenId))
        tokens.append(Int32(Qwen3AsrConfig.systemTokenId))
        tokens.append(Int32(Qwen3AsrConfig.newlineTokenId))
        tokens.append(Int32(Qwen3AsrConfig.imEndTokenId))
        tokens.append(Int32(Qwen3AsrConfig.newlineTokenId))

        // User turn with audio.
        tokens.append(Int32(Qwen3AsrConfig.imStartTokenId))
        tokens.append(Int32(Qwen3AsrConfig.userTokenId))
        tokens.append(Int32(Qwen3AsrConfig.newlineTokenId))
        tokens.append(Int32(Qwen3AsrConfig.audioStartTokenId))
        for _ in 0..<numAudioFrames {
            tokens.append(Int32(Qwen3AsrConfig.audioTokenId))
        }
        tokens.append(Int32(Qwen3AsrConfig.audioEndTokenId))
        tokens.append(Int32(Qwen3AsrConfig.imEndTokenId))
        tokens.append(Int32(Qwen3AsrConfig.newlineTokenId))

        // Assistant header.
        tokens.append(Int32(Qwen3AsrConfig.imStartTokenId))
        tokens.append(Int32(Qwen3AsrConfig.assistantTokenId))
        tokens.append(Int32(Qwen3AsrConfig.newlineTokenId))

        // Forced language: `language {Name}<asr_text>`.
        if let language, let prefix = forcedLanguagePrefixTokens[language] {
            tokens.append(contentsOf: prefix)
        }

        return tokens
    }
}
